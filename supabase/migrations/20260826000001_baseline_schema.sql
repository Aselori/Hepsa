-- ADVERTENCIA: todas estas políticas leen el rol desde el JWT
-- (user_metadata), campo que cualquier usuario puede reescribir con
-- auth.updateUser(). No protegen nada. Se reemplazan en 0002.

CREATE POLICY "Lectura publica del catalogo" ON public.products
    FOR SELECT USING (true);

CREATE POLICY "Admins pueden insertar productos" ON public.products
    FOR INSERT WITH CHECK ((((auth.jwt() -> 'user_metadata') ->> 'role') = 'admin'));

CREATE POLICY "Admins pueden editar productos" ON public.products
    FOR UPDATE USING ((((auth.jwt() -> 'user_metadata') ->> 'role') = 'admin'));

CREATE POLICY "Admins gestionan ordenes" ON public.orders
    USING ((((auth.jwt() -> 'user_metadata') ->> 'role') = 'admin'));

CREATE POLICY "Clientes ven sus ordenes" ON public.orders
    FOR SELECT USING (auth.uid() = client_id);

CREATE POLICY "Admins gestionan detalles de orden" ON public.order_items
    USING ((((auth.jwt() -> 'user_metadata') ->> 'role') = 'admin'));

CREATE POLICY "Lectura permitida para staff" ON public.profiles
    FOR SELECT USING (
        (((auth.jwt() -> 'user_metadata') ->> 'role') = 'admin')
     OR (((auth.jwt() -> 'user_metadata') ->> 'role') = 'empleado')
    );

CREATE POLICY "Public insert requests" ON public.custom_requests
    FOR INSERT WITH CHECK (true);

CREATE POLICY "Staff select requests" ON public.custom_requests
    FOR SELECT USING (
        (((auth.jwt() -> 'user_metadata') ->> 'role') = ANY (ARRAY['admin', 'empleado']))
    );

CREATE POLICY "Staff update requests" ON public.custom_requests
    FOR UPDATE USING (
        (((auth.jwt() -> 'user_metadata') ->> 'role') = ANY (ARRAY['admin', 'empleado']))
    );

