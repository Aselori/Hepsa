-- NOTA: esta versión lee el rol desde raw_user_meta_data, que el cliente
-- controla en signUp(). Es la escalada de privilegios que corrige 0002.
CREATE FUNCTION public.handle_new_user() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    AS $$
BEGIN
  INSERT INTO public.profiles (
    id, first_name, middle_name, last_name_p, last_name_m, email, phone, role
  ) VALUES (
    new.id,
    COALESCE(new.raw_user_meta_data->>'first_name', 'Sin Nombre'),
    new.raw_user_meta_data->>'middle_name',
    COALESCE(new.raw_user_meta_data->>'last_name_p', 'Sin Apellido'),
    new.raw_user_meta_data->>'last_name_m',
    new.email,
    new.raw_user_meta_data->>'phone',
    COALESCE(new.raw_user_meta_data->>'role', 'cliente')::public.user_role
  );
  RETURN new;
END;
$$;

CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

CREATE FUNCTION public.generate_employee_username() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
  IF NEW.role IN ('vendedor', 'admin') THEN
    NEW.username := LOWER(NEW.first_name) || '.' || LOWER(NEW.last_name_p);
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER tr_generate_username
    BEFORE INSERT OR UPDATE ON public.profiles
    FOR EACH ROW EXECUTE FUNCTION public.generate_employee_username();

