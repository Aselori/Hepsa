CREATE TYPE public.payment_status AS ENUM ('completo', 'anticipo', 'faltante');
CREATE TYPE public.project_status AS ENUM ('cotizando', 'en_produccion', 'instalado');
CREATE TYPE public.user_role     AS ENUM ('cliente', 'vendedor', 'admin');

-- ─── Tablas ─────────────────────────────────────────────────────────────────

CREATE TABLE public.profiles (
    id          uuid NOT NULL PRIMARY KEY,
    first_name  text NOT NULL,
    middle_name text,
    last_name_p text NOT NULL,
    last_name_m text,
    email       text NOT NULL,
    phone       text,
    role        public.user_role DEFAULT 'cliente'::public.user_role,
    username    text,
    created_at  timestamp with time zone DEFAULT now()
);

CREATE TABLE public.products (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    description text,
    price       numeric(12,2) NOT NULL,
    image_url   text,
    is_active   boolean DEFAULT true,
    created_at  timestamp with time zone DEFAULT now(),
    stock       integer DEFAULT 0
);

CREATE TABLE public.orders (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id         uuid,
    seller_id         uuid,
    subtotal          numeric(12,2) NOT NULL,
    tax               numeric(12,2) NOT NULL,
    total             numeric(12,2) NOT NULL,
    payment_status    public.payment_status DEFAULT 'anticipo'::public.payment_status,
    project_status    public.project_status DEFAULT 'cotizando'::public.project_status,
    created_at        timestamp with time zone DEFAULT now(),
    notes             text,
    client_first_name text,
    client_last_name  text,
    client_phone      text,
    client_email      text
);

CREATE TABLE public.order_items (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     bigint REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id   bigint REFERENCES public.products(id),
    custom_label text,
    quantity     integer DEFAULT 1,
    unit_price   numeric(12,2) NOT NULL
);

CREATE TABLE public.custom_requests (
    id             uuid DEFAULT gen_random_uuid() NOT NULL PRIMARY KEY,
    first_name     text,
    middle_name    text,
    last_name_p    text,
    last_name_m    text,
    email          text,
    phone          text,
    specifications text,
    status         text DEFAULT 'Pendiente de Revisión'::text,
    created_at     timestamp with time zone DEFAULT timezone('utc'::text, now())
);

