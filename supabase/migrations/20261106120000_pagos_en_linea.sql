-- ============================================================================
-- PAGOS EN LÍNEA (Mejora 2): registrar lo que Stripe confirma
--
-- El cobro no pasa por el navegador ni por esta base: Stripe cobra y avisa a
-- la Edge Function webhook-stripe, que verifica la firma y llama a
-- registrar_pago_en_linea(). Esta migración deja dos cosas:
--
--   1. La tabla pagos, un renglón por sesión de Stripe. sesion_id es UNIQUE
--      porque Stripe reintenta el aviso hasta recibir un 2xx: el mismo pago
--      puede llegar dos veces y no debe contarse dos veces.
--   2. La función que marca el pedido pagado y descuenta existencias, todo o
--      nada. El checkout (20260827000006) dejó escrito que el descuento
--      pertenece al momento en que se confirma el pago: es este.
--
-- Nadie la llama desde el navegador. Sólo service_role, que vive en la Edge
-- Function y nunca llega al cliente.
-- ============================================================================

CREATE TABLE public.pagos (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   bigint NOT NULL REFERENCES public.orders(id) ON DELETE RESTRICT,
    proveedor  text NOT NULL DEFAULT 'stripe',
    sesion_id  text NOT NULL UNIQUE,
    monto      numeric(12,2) NOT NULL CHECK (monto > 0),
    moneda     text NOT NULL DEFAULT 'mxn',
    -- Un segundo pago completo del mismo pedido (dos pestañas pagando a la
    -- vez) se guarda igual, porque el dinero ya se cobró, pero marcado para
    -- que el personal lo reembolse.
    duplicado  boolean NOT NULL DEFAULT false,
    creado     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX pagos_order_id_idx ON public.pagos (order_id);

ALTER TABLE public.pagos ENABLE ROW LEVEL SECURITY;

-- Lectura: el personal ve todos; el cliente, los de sus pedidos. No hay
-- políticas de escritura: sólo la función de abajo inserta.
CREATE POLICY "pagos_select_staff" ON public.pagos
    FOR SELECT TO authenticated USING (public.is_staff());

CREATE POLICY "pagos_select_propios" ON public.pagos
    FOR SELECT TO authenticated USING (
        EXISTS (SELECT 1 FROM public.orders o
                 WHERE o.id = pagos.order_id AND o.client_id = auth.uid()));

REVOKE ALL ON public.pagos FROM anon, authenticated;
GRANT SELECT ON public.pagos TO authenticated;

-- ─── Registrar un pago confirmado ───────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.registrar_pago_en_linea(
    p_pedido bigint, p_sesion text, p_monto numeric, p_moneda text)
    RETURNS text
    LANGUAGE plpgsql
    SECURITY DEFINER
    SET search_path = public
    AS $$
DECLARE
  v_pedido public.orders%ROWTYPE;
BEGIN
  -- FOR UPDATE: dos avisos simultáneos del mismo pedido esperan su turno, así
  -- que el segundo ve el estado que dejó el primero.
  SELECT * INTO v_pedido FROM public.orders WHERE id = p_pedido FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'El pedido % no existe', p_pedido;
  END IF;

  IF EXISTS (SELECT 1 FROM public.pagos WHERE sesion_id = p_sesion) THEN
    RETURN 'repetido';
  END IF;

  -- El monto lo fijó crear-pago a partir de orders.total. Si no coincide, algo
  -- cambió el pedido entre el cobro y el aviso, o el aviso no es de este
  -- pedido. Fallar hace que Stripe reintente y que el error se vea en su
  -- panel, en vez de marcar pagado un pedido que no lo está.
  IF lower(p_moneda) <> 'mxn' OR p_monto <> v_pedido.total THEN
    RAISE EXCEPTION 'El pago (% %) no coincide con el total del pedido % (% mxn)',
      p_monto, p_moneda, p_pedido, v_pedido.total;
  END IF;

  IF v_pedido.payment_status = 'completo' THEN
    INSERT INTO public.pagos (order_id, sesion_id, monto, moneda, duplicado)
    VALUES (p_pedido, p_sesion, p_monto, lower(p_moneda), true);
    RETURN 'duplicado';
  END IF;

  INSERT INTO public.pagos (order_id, sesion_id, monto, moneda)
  VALUES (p_pedido, p_sesion, p_monto, lower(p_moneda));

  UPDATE public.orders SET payment_status = 'completo' WHERE id = p_pedido;

  -- Sin bajar de cero: si el inventario cambió desde el checkout, el cobro ya
  -- ocurrió y el pedido se atiende igual; el personal ve el stock en 0.
  UPDATE public.products p
     SET stock = GREATEST(COALESCE(p.stock, 0) - oi.quantity, 0)
    FROM public.order_items oi
   WHERE oi.order_id = p_pedido AND oi.product_id = p.id;

  RETURN 'pagado';
END;
$$;

REVOKE EXECUTE ON FUNCTION public.registrar_pago_en_linea(bigint, text, numeric, text)
    FROM public, anon, authenticated;
GRANT  EXECUTE ON FUNCTION public.registrar_pago_en_linea(bigint, text, numeric, text)
    TO service_role;
